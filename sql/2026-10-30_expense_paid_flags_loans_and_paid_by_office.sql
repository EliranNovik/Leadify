-- Expenses: paid/unpaid tracking on every rubric, plus two new rubrics.
--
-- 1. Every expense table gains `paid boolean`, so All Expenses can split each category into
--    paid and unpaid and total what is still owed.
-- 2. Loans the firm took: `loans` holds the loan, `loan_payment_expense` holds the monthly
--    repayment that counts as an expense (same shape as rent and partner draws).
-- 3. `paid_by_office_expense`: client expenses the office had to take over because the client
--    never paid, linked to the lead so the debt can be chased.
--
-- Rows that exist when this runs are marked paid, on the assumption that past months are
-- settled; otherwise the debt box would open showing the firm's whole history as owed.
-- Drop the two UPDATE statements below if that is wrong for your data.

-- ---------------------------------------------------------------------------
-- 1. paid flags on the existing rubrics
-- ---------------------------------------------------------------------------

ALTER TABLE public.source_media_expense
  ADD COLUMN IF NOT EXISTS paid boolean NOT NULL DEFAULT false;

ALTER TABLE public.office_rent_expense
  ADD COLUMN IF NOT EXISTS paid boolean NOT NULL DEFAULT false;

ALTER TABLE public.partner_draw_expense
  ADD COLUMN IF NOT EXISTS paid boolean NOT NULL DEFAULT false;

ALTER TABLE public.firm_management_costs
  ADD COLUMN IF NOT EXISTS paid boolean NOT NULL DEFAULT false;

ALTER TABLE public.employee_salary
  ADD COLUMN IF NOT EXISTS paid boolean NOT NULL DEFAULT false;

COMMENT ON COLUMN public.source_media_expense.paid IS 'The firm has settled this line.';
COMMENT ON COLUMN public.office_rent_expense.paid IS 'The firm has settled this line.';
COMMENT ON COLUMN public.partner_draw_expense.paid IS 'The firm has settled this line.';
COMMENT ON COLUMN public.firm_management_costs.paid IS 'The firm has settled this line.';
COMMENT ON COLUMN public.employee_salary.paid IS
  'The salary has been paid out. Separate from `approved`, which is the payroll import check.';

-- Unpaid rows are the ones the debt box reads, and they are the small minority.
CREATE INDEX IF NOT EXISTS idx_source_media_expense_unpaid
  ON public.source_media_expense (expense_month) WHERE NOT paid;
CREATE INDEX IF NOT EXISTS idx_office_rent_expense_unpaid
  ON public.office_rent_expense (expense_month) WHERE NOT paid;
CREATE INDEX IF NOT EXISTS idx_partner_draw_expense_unpaid
  ON public.partner_draw_expense (expense_month) WHERE NOT paid;
CREATE INDEX IF NOT EXISTS idx_firm_management_costs_unpaid
  ON public.firm_management_costs (billing_month) WHERE NOT paid;
CREATE INDEX IF NOT EXISTS idx_employee_salary_unpaid
  ON public.employee_salary (salary_year, salary_month) WHERE NOT paid;

-- ---------------------------------------------------------------------------
-- 2. Loans
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public.loans (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  lender text NOT NULL,
  principal_nis numeric(14, 2) NOT NULL DEFAULT 0 CHECK (principal_nis >= 0),
  started_on date,
  notes text,
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  created_by uuid REFERENCES auth.users (id) ON DELETE SET NULL,
  updated_at timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE public.loans IS 'Loans the firm took: who lent the money and how much.';
COMMENT ON COLUMN public.loans.principal_nis IS 'Total borrowed, in NIS. Repayments live in loan_payment_expense.';
COMMENT ON COLUMN public.loans.is_active IS 'False once the loan is fully repaid; keeps it out of the add-expense picker.';

CREATE TABLE IF NOT EXISTS public.loan_payment_expense (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  loan_id uuid NOT NULL REFERENCES public.loans (id) ON DELETE RESTRICT,
  expense_month date NOT NULL,
  amount_nis numeric(14, 2) NOT NULL CHECK (amount_nis >= 0),
  due_date date,
  paid boolean NOT NULL DEFAULT false,
  notes text,
  created_at timestamptz NOT NULL DEFAULT now(),
  created_by uuid REFERENCES auth.users (id) ON DELETE SET NULL,
  CONSTRAINT loan_payment_expense_loan_month_key UNIQUE (loan_id, expense_month),
  CONSTRAINT loan_payment_expense_month_first_day_chk
    CHECK (date_trunc('month', expense_month::timestamp)::date = expense_month)
);

COMMENT ON TABLE public.loan_payment_expense IS 'One repayment per loan per month; this is what the expense reports total.';
COMMENT ON COLUMN public.loan_payment_expense.expense_month IS 'First calendar day of the month (YYYY-MM-01).';
COMMENT ON COLUMN public.loan_payment_expense.due_date IS
  'When the repayment is due. Empty means due at the end of expense_month.';

CREATE INDEX IF NOT EXISTS idx_loan_payment_expense_loan
  ON public.loan_payment_expense (loan_id);
CREATE INDEX IF NOT EXISTS idx_loan_payment_expense_month
  ON public.loan_payment_expense (expense_month DESC);
CREATE INDEX IF NOT EXISTS idx_loan_payment_expense_unpaid
  ON public.loan_payment_expense (expense_month) WHERE NOT paid;

-- ---------------------------------------------------------------------------
-- 3. Expenses the office took over from clients
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public.paid_by_office_expense (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  expense_date date NOT NULL DEFAULT current_date,
  amount numeric(14, 2) NOT NULL CHECK (amount >= 0),
  currency text NOT NULL DEFAULT 'ILS',
  new_lead_id uuid REFERENCES public.leads (id) ON DELETE SET NULL,
  legacy_lead_id bigint REFERENCES public.leads_lead (id) ON DELETE SET NULL,
  lead_number text,
  description text,
  paid boolean NOT NULL DEFAULT false,
  reimbursed boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  created_by uuid REFERENCES auth.users (id) ON DELETE SET NULL,
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT paid_by_office_expense_one_lead CHECK (
    NOT (new_lead_id IS NOT NULL AND legacy_lead_id IS NOT NULL)
  )
);

COMMENT ON TABLE public.paid_by_office_expense IS
  'Case expenses the office had to cover because the client did not pay.';
COMMENT ON COLUMN public.paid_by_office_expense.paid IS 'The office has actually paid this out.';
COMMENT ON COLUMN public.paid_by_office_expense.reimbursed IS
  'The client has since paid the office back. Tracked separately from paid: the firm owes the supplier, the client owes the firm.';

CREATE INDEX IF NOT EXISTS idx_paid_by_office_expense_date
  ON public.paid_by_office_expense (expense_date DESC);
CREATE INDEX IF NOT EXISTS idx_paid_by_office_expense_new_lead
  ON public.paid_by_office_expense (new_lead_id) WHERE new_lead_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_paid_by_office_expense_legacy_lead
  ON public.paid_by_office_expense (legacy_lead_id) WHERE legacy_lead_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_paid_by_office_expense_unpaid
  ON public.paid_by_office_expense (expense_date) WHERE NOT paid;

-- ---------------------------------------------------------------------------
-- 4. Audit defaults, RLS and grants for the new tables
-- ---------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.set_expense_row_audit()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    IF NEW.created_by IS NULL THEN
      NEW.created_by := auth.uid();
    END IF;
  END IF;
  RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.touch_expense_row_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_loans_audit ON public.loans;
CREATE TRIGGER trg_loans_audit
  BEFORE INSERT ON public.loans
  FOR EACH ROW EXECUTE FUNCTION public.set_expense_row_audit();

DROP TRIGGER IF EXISTS trg_loans_touch ON public.loans;
CREATE TRIGGER trg_loans_touch
  BEFORE UPDATE ON public.loans
  FOR EACH ROW EXECUTE FUNCTION public.touch_expense_row_updated_at();

DROP TRIGGER IF EXISTS trg_loan_payment_expense_audit ON public.loan_payment_expense;
CREATE TRIGGER trg_loan_payment_expense_audit
  BEFORE INSERT ON public.loan_payment_expense
  FOR EACH ROW EXECUTE FUNCTION public.set_expense_row_audit();

DROP TRIGGER IF EXISTS trg_paid_by_office_expense_audit ON public.paid_by_office_expense;
CREATE TRIGGER trg_paid_by_office_expense_audit
  BEFORE INSERT ON public.paid_by_office_expense
  FOR EACH ROW EXECUTE FUNCTION public.set_expense_row_audit();

DROP TRIGGER IF EXISTS trg_paid_by_office_expense_touch ON public.paid_by_office_expense;
CREATE TRIGGER trg_paid_by_office_expense_touch
  BEFORE UPDATE ON public.paid_by_office_expense
  FOR EACH ROW EXECUTE FUNCTION public.touch_expense_row_updated_at();

ALTER TABLE public.loans ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.loan_payment_expense ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.paid_by_office_expense ENABLE ROW LEVEL SECURITY;

DO $$
DECLARE
  t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['loans', 'loan_payment_expense', 'paid_by_office_expense'] LOOP
    EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I', t || '_select', t);
    EXECUTE format(
      'CREATE POLICY %I ON public.%I FOR SELECT TO authenticated USING (true)',
      t || '_select', t);

    EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I', t || '_insert', t);
    EXECUTE format(
      'CREATE POLICY %I ON public.%I FOR INSERT TO authenticated WITH CHECK (auth.uid() IS NOT NULL)',
      t || '_insert', t);

    EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I', t || '_update', t);
    EXECUTE format(
      'CREATE POLICY %I ON public.%I FOR UPDATE TO authenticated USING (auth.uid() IS NOT NULL) WITH CHECK (auth.uid() IS NOT NULL)',
      t || '_update', t);

    EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I', t || '_delete', t);
    EXECUTE format(
      'CREATE POLICY %I ON public.%I FOR DELETE TO authenticated USING (auth.uid() IS NOT NULL)',
      t || '_delete', t);

    EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON public.%I TO authenticated', t);
  END LOOP;
END;
$$;

