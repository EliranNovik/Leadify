-- Employee roles catalog (id PK) + FK from tenants_employee.
-- Shared client helpers: src/lib/employeeRoles.ts
-- Admin UI: EmployeeRolesManager

-- Recreate catalog (safe if prior code-PK version was applied)
DROP TABLE IF EXISTS public.employee_roles CASCADE;

CREATE TABLE public.employee_roles (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code text NOT NULL,
  name text NOT NULL,
  sort_order integer NOT NULL DEFAULT 100,
  is_selectable boolean NOT NULL DEFAULT true,
  alias_of_id bigint NULL REFERENCES public.employee_roles (id) ON DELETE SET NULL,
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT employee_roles_code_unique UNIQUE (code),
  CONSTRAINT employee_roles_name_not_blank CHECK (char_length(trim(name)) > 0),
  CONSTRAINT employee_roles_code_not_blank CHECK (char_length(trim(code)) > 0),
  CONSTRAINT employee_roles_alias_not_self CHECK (alias_of_id IS NULL OR alias_of_id <> id)
);

CREATE INDEX idx_employee_roles_selectable
  ON public.employee_roles (is_selectable, sort_order)
  WHERE is_active;

CREATE INDEX idx_employee_roles_alias_of_id
  ON public.employee_roles (alias_of_id)
  WHERE alias_of_id IS NOT NULL;

CREATE INDEX idx_employee_roles_active_name
  ON public.employee_roles (is_active, name);

COMMENT ON TABLE public.employee_roles IS
  'Catalog of employee bonuses/org roles. tenants_employee.bonuses_role_id → employee_roles.id; bonuses_role text stays synced to code.';

