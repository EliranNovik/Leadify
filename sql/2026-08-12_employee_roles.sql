-- Link employees → roles
ALTER TABLE public.tenants_employee
  ADD COLUMN IF NOT EXISTS bonuses_role_id bigint;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_constraint
    WHERE conname = 'tenants_employee_bonuses_role_id_fkey'
  ) THEN
    ALTER TABLE public.tenants_employee
      ADD CONSTRAINT tenants_employee_bonuses_role_id_fkey
      FOREIGN KEY (bonuses_role_id)
      REFERENCES public.employee_roles (id)
      ON DELETE SET NULL;
  END IF;
END $$;

CREATE INDEX IF NOT EXISTS idx_tenants_employee_bonuses_role_id
  ON public.tenants_employee (bonuses_role_id);

-- Backfill role ids from existing text codes (exact, then lower)
UPDATE public.tenants_employee te
SET bonuses_role_id = r.id
FROM public.employee_roles r
WHERE te.bonuses_role_id IS NULL
  AND te.bonuses_role IS NOT NULL
  AND trim(te.bonuses_role) <> ''
  AND r.code = trim(te.bonuses_role);

UPDATE public.tenants_employee te
SET bonuses_role_id = r.id
FROM public.employee_roles r
WHERE te.bonuses_role_id IS NULL
  AND te.bonuses_role IS NOT NULL
  AND trim(te.bonuses_role) <> ''
  AND lower(r.code) = lower(trim(te.bonuses_role));

-- Keep bonuses_role text in sync with selected role id (legacy readers keep working)
CREATE OR REPLACE FUNCTION public.sync_tenants_employee_bonuses_role_from_id()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  IF NEW.bonuses_role_id IS NULL THEN
    RETURN NEW;
  END IF;

  SELECT r.code
    INTO NEW.bonuses_role
  FROM public.employee_roles r
  WHERE r.id = NEW.bonuses_role_id;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_sync_tenants_employee_bonuses_role ON public.tenants_employee;
CREATE TRIGGER trg_sync_tenants_employee_bonuses_role
  BEFORE INSERT OR UPDATE OF bonuses_role_id
  ON public.tenants_employee
  FOR EACH ROW
  EXECUTE FUNCTION public.sync_tenants_employee_bonuses_role_from_id();

-- If only text role is written, resolve id when possible
CREATE OR REPLACE FUNCTION public.sync_tenants_employee_bonuses_role_id_from_code()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  IF NEW.bonuses_role_id IS NOT NULL THEN
    RETURN NEW;
  END IF;
  IF NEW.bonuses_role IS NULL OR trim(NEW.bonuses_role) = '' THEN
    RETURN NEW;
  END IF;

  SELECT r.id
    INTO NEW.bonuses_role_id
  FROM public.employee_roles r
  WHERE r.code = trim(NEW.bonuses_role)
     OR lower(r.code) = lower(trim(NEW.bonuses_role))
  ORDER BY CASE WHEN r.code = trim(NEW.bonuses_role) THEN 0 ELSE 1 END
  LIMIT 1;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_sync_tenants_employee_bonuses_role_id ON public.tenants_employee;
CREATE TRIGGER trg_sync_tenants_employee_bonuses_role_id
  BEFORE INSERT OR UPDATE OF bonuses_role
  ON public.tenants_employee
  FOR EACH ROW
  EXECUTE FUNCTION public.sync_tenants_employee_bonuses_role_id_from_code();

