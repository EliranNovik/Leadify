-- Helper Handler: a lead role that several employees can hold at once.
--
-- Every other role on a lead is one column holding one person, which cannot express "these four
-- people are helper handlers". So the assignments live in their own table, one row per employee per
-- lead, following the `lead_sub_efforts` shape already used for per-lead/per-employee data: a
-- `new_lead_id` uuid for leads, a `legacy_lead_id` bigint for leads_lead, exactly one of the two set.
--
-- About the column on leads / leads_lead
-- --------------------------------------
-- `helper_handler_ids` is a derived copy, not a second place to record the fact. Reports, exports and
-- list views read roles straight off the lead row, and none of them can join a side table; this gives
-- them the role without every one of them having to change.
--
-- It is maintained by trigger rather than by the app, deliberately. The same fact written to two
-- places by application code is how `sent_to_finance` and `invoice_sent` drifted apart badly enough
-- to need two repair migrations this week. Here the table is the only thing anyone writes, and the
-- column cannot disagree with it.
--
-- Ids rather than names, for the same reason the other id-backed roles store ids: an employee who
-- changes their display name would otherwise leave stale text behind on every lead they touch.

BEGIN;

CREATE TABLE IF NOT EXISTS public.lead_helper_handlers (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  new_lead_id uuid NULL REFERENCES public.leads (id) ON DELETE CASCADE,
  -- No FK: `leads_lead` is the legacy table and the rest of the schema does not constrain against it.
  legacy_lead_id bigint NULL,
  employee_id bigint NOT NULL REFERENCES public.tenants_employee (id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  created_by text NULL,
  CONSTRAINT lead_helper_handlers_one_lead CHECK (
    (new_lead_id IS NOT NULL AND legacy_lead_id IS NULL)
    OR (new_lead_id IS NULL AND legacy_lead_id IS NOT NULL)
  )
);

COMMENT ON TABLE public.lead_helper_handlers IS
  'Helper Handler role assignments. Several employees may hold this role on one lead. Source of truth for leads.helper_handler_ids / leads_lead.helper_handler_ids, which a trigger keeps in step.';

-- One row per employee per lead. Partial so each index only covers the rows that use that lead key.
CREATE UNIQUE INDEX IF NOT EXISTS lead_helper_handlers_new_lead_employee_key
  ON public.lead_helper_handlers (new_lead_id, employee_id)
  WHERE new_lead_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS lead_helper_handlers_legacy_lead_employee_key
  ON public.lead_helper_handlers (legacy_lead_id, employee_id)
  WHERE legacy_lead_id IS NOT NULL;

-- "Which leads is this employee a helper handler on", which is the other direction reports will ask.
CREATE INDEX IF NOT EXISTS idx_lead_helper_handlers_employee
  ON public.lead_helper_handlers (employee_id);

ALTER TABLE public.leads
  ADD COLUMN IF NOT EXISTS helper_handler_ids bigint[] NOT NULL DEFAULT '{}'::bigint[];
ALTER TABLE public.leads_lead
  ADD COLUMN IF NOT EXISTS helper_handler_ids bigint[] NOT NULL DEFAULT '{}'::bigint[];

COMMENT ON COLUMN public.leads.helper_handler_ids IS
  'Derived from lead_helper_handlers by trigger. Read freely; never write directly — insert/delete the table rows instead.';
COMMENT ON COLUMN public.leads_lead.helper_handler_ids IS
  'Derived from lead_helper_handlers by trigger. Read freely; never write directly — insert/delete the table rows instead.';

/*
 * Recompute one lead's column from the table.
 *
 * Takes both keys and ignores the null one, so the trigger can call it for OLD and NEW without
 * caring which kind of lead the row belongs to.
 */
CREATE OR REPLACE FUNCTION public.lead_helper_handlers_refresh(
  p_new_lead_id uuid,
  p_legacy_lead_id bigint
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF p_new_lead_id IS NOT NULL THEN
    UPDATE public.leads
    SET helper_handler_ids = COALESCE(
      (
        SELECT array_agg(h.employee_id ORDER BY h.employee_id)
        FROM public.lead_helper_handlers h
        WHERE h.new_lead_id = p_new_lead_id
      ),
      '{}'::bigint[]
    )
    WHERE id = p_new_lead_id;
  END IF;

  IF p_legacy_lead_id IS NOT NULL THEN
    UPDATE public.leads_lead
    SET helper_handler_ids = COALESCE(
      (
        SELECT array_agg(h.employee_id ORDER BY h.employee_id)
        FROM public.lead_helper_handlers h
        WHERE h.legacy_lead_id = p_legacy_lead_id
      ),
      '{}'::bigint[]
    )
    WHERE id = p_legacy_lead_id;
  END IF;
END;
$$;

CREATE OR REPLACE FUNCTION public.lead_helper_handlers_sync()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  -- NEW is unset on DELETE and OLD on INSERT, so each is only touched where it exists. An UPDATE
  -- that moved the row to another lead has to refresh both, which is why both run on UPDATE.
  IF TG_OP IN ('DELETE', 'UPDATE') THEN
    PERFORM public.lead_helper_handlers_refresh(OLD.new_lead_id, OLD.legacy_lead_id);
  END IF;
  IF TG_OP IN ('INSERT', 'UPDATE') THEN
    PERFORM public.lead_helper_handlers_refresh(NEW.new_lead_id, NEW.legacy_lead_id);
  END IF;
  RETURN NULL;
END;
$$;

DROP TRIGGER IF EXISTS lead_helper_handlers_sync ON public.lead_helper_handlers;
CREATE TRIGGER lead_helper_handlers_sync
AFTER INSERT OR UPDATE OR DELETE ON public.lead_helper_handlers
FOR EACH ROW EXECUTE FUNCTION public.lead_helper_handlers_sync();

ALTER TABLE public.lead_helper_handlers ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "lead_helper_handlers_authenticated_select" ON public.lead_helper_handlers;
DROP POLICY IF EXISTS "lead_helper_handlers_authenticated_insert" ON public.lead_helper_handlers;
DROP POLICY IF EXISTS "lead_helper_handlers_authenticated_update" ON public.lead_helper_handlers;
DROP POLICY IF EXISTS "lead_helper_handlers_authenticated_delete" ON public.lead_helper_handlers;

CREATE POLICY "lead_helper_handlers_authenticated_select" ON public.lead_helper_handlers
  FOR SELECT TO authenticated USING (true);
CREATE POLICY "lead_helper_handlers_authenticated_insert" ON public.lead_helper_handlers
  FOR INSERT TO authenticated WITH CHECK (true);
CREATE POLICY "lead_helper_handlers_authenticated_update" ON public.lead_helper_handlers
  FOR UPDATE TO authenticated USING (true) WITH CHECK (true);
CREATE POLICY "lead_helper_handlers_authenticated_delete" ON public.lead_helper_handlers
  FOR DELETE TO authenticated USING (true);

GRANT SELECT, INSERT, UPDATE, DELETE ON public.lead_helper_handlers TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.lead_helper_handlers_id_seq TO authenticated;

COMMIT;

NOTIFY pgrst, 'reload schema';

