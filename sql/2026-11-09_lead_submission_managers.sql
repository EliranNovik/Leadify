-- Submission Manager can be held by several employees on one lead, the same way
-- Helper Handler is. The table is the source of truth. submission_manager_ids is a
-- derived copy for lists that read the lead row. submission_manager_id stays the
-- first of those people so the header and stage chip still have one person.

BEGIN;

CREATE TABLE IF NOT EXISTS public.lead_submission_managers (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  new_lead_id uuid NULL REFERENCES public.leads (id) ON DELETE CASCADE,
  legacy_lead_id bigint NULL,
  employee_id bigint NOT NULL REFERENCES public.tenants_employee (id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  created_by text NULL,
  CONSTRAINT lead_submission_managers_one_lead CHECK (
    (new_lead_id IS NOT NULL AND legacy_lead_id IS NULL)
    OR (new_lead_id IS NULL AND legacy_lead_id IS NOT NULL)
  )
);

COMMENT ON TABLE public.lead_submission_managers IS
  'Submission Manager assignments. Several employees may hold this role on one lead. Source of truth for submission_manager_ids, and for submission_manager_id (the first employee).';

CREATE UNIQUE INDEX IF NOT EXISTS lead_submission_managers_new_lead_employee_key
  ON public.lead_submission_managers (new_lead_id, employee_id)
  WHERE new_lead_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS lead_submission_managers_legacy_lead_employee_key
  ON public.lead_submission_managers (legacy_lead_id, employee_id)
  WHERE legacy_lead_id IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_lead_submission_managers_employee
  ON public.lead_submission_managers (employee_id);

ALTER TABLE public.leads
  ADD COLUMN IF NOT EXISTS submission_manager_ids bigint[] NOT NULL DEFAULT '{}'::bigint[];
ALTER TABLE public.leads_lead
  ADD COLUMN IF NOT EXISTS submission_manager_ids bigint[] NOT NULL DEFAULT '{}'::bigint[];

COMMENT ON COLUMN public.leads.submission_manager_ids IS
  'Derived from lead_submission_managers by trigger. Read freely; insert or delete table rows instead of writing this.';
COMMENT ON COLUMN public.leads_lead.submission_manager_ids IS
  'Derived from lead_submission_managers by trigger. Read freely; insert or delete table rows instead of writing this.';

CREATE OR REPLACE FUNCTION public.lead_submission_managers_refresh(
  p_new_lead_id uuid,
  p_legacy_lead_id bigint
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_ids bigint[];
BEGIN
  IF p_new_lead_id IS NOT NULL THEN
    SELECT COALESCE(array_agg(h.employee_id ORDER BY h.employee_id), '{}'::bigint[])
      INTO v_ids
    FROM public.lead_submission_managers h
    WHERE h.new_lead_id = p_new_lead_id;

    UPDATE public.leads
    SET submission_manager_ids = v_ids,
        submission_manager_id = v_ids[1]
    WHERE id = p_new_lead_id;
  END IF;

  IF p_legacy_lead_id IS NOT NULL THEN
    SELECT COALESCE(array_agg(h.employee_id ORDER BY h.employee_id), '{}'::bigint[])
      INTO v_ids
    FROM public.lead_submission_managers h
    WHERE h.legacy_lead_id = p_legacy_lead_id;

    UPDATE public.leads_lead
    SET submission_manager_ids = v_ids,
        submission_manager_id = v_ids[1]
    WHERE id = p_legacy_lead_id;
  END IF;
END;
$$;

CREATE OR REPLACE FUNCTION public.lead_submission_managers_sync()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF TG_OP IN ('DELETE', 'UPDATE') THEN
    PERFORM public.lead_submission_managers_refresh(OLD.new_lead_id, OLD.legacy_lead_id);
  END IF;
  IF TG_OP IN ('INSERT', 'UPDATE') THEN
    PERFORM public.lead_submission_managers_refresh(NEW.new_lead_id, NEW.legacy_lead_id);
  END IF;
  RETURN NULL;
END;
$$;

DROP TRIGGER IF EXISTS lead_submission_managers_sync ON public.lead_submission_managers;
CREATE TRIGGER lead_submission_managers_sync
AFTER INSERT OR UPDATE OR DELETE ON public.lead_submission_managers
FOR EACH ROW EXECUTE FUNCTION public.lead_submission_managers_sync();

INSERT INTO public.lead_submission_managers (new_lead_id, employee_id)
SELECT lead.id, lead.submission_manager_id
FROM public.leads AS lead
WHERE lead.submission_manager_id IS NOT NULL
  AND NOT EXISTS (
    SELECT 1
    FROM public.lead_submission_managers AS existing
    WHERE existing.new_lead_id = lead.id
      AND existing.employee_id = lead.submission_manager_id
  );

INSERT INTO public.lead_submission_managers (legacy_lead_id, employee_id)
SELECT lead.id, lead.submission_manager_id
FROM public.leads_lead AS lead
WHERE lead.submission_manager_id IS NOT NULL
  AND NOT EXISTS (
    SELECT 1
    FROM public.lead_submission_managers AS existing
    WHERE existing.legacy_lead_id = lead.id
      AND existing.employee_id = lead.submission_manager_id
  );

ALTER TABLE public.lead_submission_managers ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "lead_submission_managers_authenticated_select" ON public.lead_submission_managers;
DROP POLICY IF EXISTS "lead_submission_managers_authenticated_insert" ON public.lead_submission_managers;
DROP POLICY IF EXISTS "lead_submission_managers_authenticated_update" ON public.lead_submission_managers;
DROP POLICY IF EXISTS "lead_submission_managers_authenticated_delete" ON public.lead_submission_managers;

CREATE POLICY "lead_submission_managers_authenticated_select" ON public.lead_submission_managers
  FOR SELECT TO authenticated USING (true);
CREATE POLICY "lead_submission_managers_authenticated_insert" ON public.lead_submission_managers
  FOR INSERT TO authenticated WITH CHECK (true);
CREATE POLICY "lead_submission_managers_authenticated_update" ON public.lead_submission_managers
  FOR UPDATE TO authenticated USING (true) WITH CHECK (true);
CREATE POLICY "lead_submission_managers_authenticated_delete" ON public.lead_submission_managers
  FOR DELETE TO authenticated USING (true);

GRANT SELECT, INSERT, UPDATE, DELETE ON public.lead_submission_managers TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.lead_submission_managers_id_seq TO authenticated;

COMMIT;

