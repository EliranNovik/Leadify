-- Efforts added from the allocation page. Shown collapsed under More. Re-run is safe.
CREATE TABLE IF NOT EXISTS public.employee_work_efforts (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    area text NOT NULL CHECK (area IN ('marketing', 'sales', 'finances', 'development')),
    name text NOT NULL CHECK (char_length(btrim(name)) >= 2),
    created_by bigint DEFAULT current_user_employee_id() REFERENCES public.tenants_employee (id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS employee_work_efforts_area_name_key
    ON public.employee_work_efforts (area, lower(btrim(name)));

ALTER TABLE public.employee_work_efforts ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Authenticated read work efforts"
    ON public.employee_work_efforts;
CREATE POLICY "Authenticated read work efforts"
    ON public.employee_work_efforts FOR SELECT
    TO authenticated
    USING (true);

DROP POLICY IF EXISTS "Authenticated add work efforts"
    ON public.employee_work_efforts;
CREATE POLICY "Authenticated add work efforts"
    ON public.employee_work_efforts FOR INSERT
    TO authenticated
    WITH CHECK (true);

GRANT SELECT, INSERT ON public.employee_work_efforts TO authenticated;

-- Where today's meetings were filed, or why they were set aside. Re-run is safe.
CREATE TABLE IF NOT EXISTS public.employee_daily_meeting_allocations (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    employee_id bigint NOT NULL REFERENCES public.tenants_employee (id) ON DELETE CASCADE,
    work_date date NOT NULL,
    meeting_id bigint NOT NULL REFERENCES public.meetings (id) ON DELETE CASCADE,
    area text NULL CHECK (area IN ('marketing', 'sales', 'finances', 'development')),
    disregard text NULL CHECK (disregard IN ('didnt_participate', 'client_no_show')),
    CONSTRAINT employee_daily_meeting_allocations_pkey PRIMARY KEY (id),
    CONSTRAINT employee_daily_meeting_allocations_employee_day_meeting_key
        UNIQUE (employee_id, work_date, meeting_id),
    CONSTRAINT employee_daily_meeting_allocations_one_choice_chk
        CHECK (area IS NULL OR disregard IS NULL)
);

ALTER TABLE public.employee_daily_meeting_allocations ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Employees manage own meeting allocations"
    ON public.employee_daily_meeting_allocations;
CREATE POLICY "Employees manage own meeting allocations"
    ON public.employee_daily_meeting_allocations FOR ALL
    TO authenticated
    USING (employee_id = current_user_employee_id())
    WITH CHECK (employee_id = current_user_employee_id());

GRANT SELECT, INSERT, UPDATE, DELETE ON public.employee_daily_meeting_allocations TO authenticated;

