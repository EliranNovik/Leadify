    END IF;
END $$;

ALTER TABLE public.employee_daily_effort_allocation_items ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Employees manage own effort allocations"
    ON public.employee_daily_effort_allocation_items;
CREATE POLICY "Employees manage own effort allocations"
    ON public.employee_daily_effort_allocation_items FOR ALL
    TO authenticated
    USING (
        EXISTS (
            SELECT 1
            FROM public.employee_daily_lead_allocations a
            WHERE a.id = allocation_id
              AND a.employee_id = current_user_employee_id()
        )
    )
    WITH CHECK (
        EXISTS (
            SELECT 1
            FROM public.employee_daily_lead_allocations a
            WHERE a.id = allocation_id
              AND a.employee_id = current_user_employee_id()
        )
    );

DROP POLICY IF EXISTS "Superusers view all effort allocations"
    ON public.employee_daily_effort_allocation_items;
CREATE POLICY "Superusers view all effort allocations"
    ON public.employee_daily_effort_allocation_items FOR SELECT
    TO authenticated
    USING (is_app_superuser());

GRANT SELECT, INSERT, UPDATE, DELETE ON public.employee_daily_effort_allocation_items TO authenticated;

