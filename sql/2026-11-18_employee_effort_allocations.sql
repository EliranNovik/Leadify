-- Time allocated to Marketing, Sales, Finances, and Development efforts.
-- Shares the daily allocation header with lead (Handling) allocations.
-- Run in the Supabase SQL editor.

CREATE TABLE IF NOT EXISTS public.employee_daily_effort_allocation_items (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    allocation_id bigint NOT NULL,
    area text NOT NULL CHECK (area IN ('marketing', 'sales', 'finances', 'development')),
    effort_id text NOT NULL,
    percent numeric(5, 2) NOT NULL CHECK (percent > 0 AND percent <= 100),
    department_id bigint,
    CONSTRAINT employee_daily_effort_allocation_items_pkey PRIMARY KEY (id),
    CONSTRAINT employee_daily_effort_allocation_items_department_id_fkey
        FOREIGN KEY (department_id) REFERENCES public.tenant_departement(id) ON DELETE SET NULL,
    CONSTRAINT employee_daily_effort_allocation_items_allocation_id_fkey
        FOREIGN KEY (allocation_id) REFERENCES public.employee_daily_lead_allocations(id) ON DELETE CASCADE,
    CONSTRAINT employee_daily_effort_allocation_items_allocation_effort_key
        UNIQUE (allocation_id, effort_id)
);

CREATE INDEX IF NOT EXISTS idx_employee_daily_effort_allocation_items_allocation
    ON public.employee_daily_effort_allocation_items(allocation_id);

CREATE INDEX IF NOT EXISTS idx_employee_daily_effort_allocation_items_area
    ON public.employee_daily_effort_allocation_items(area);

COMMENT ON TABLE public.employee_daily_effort_allocation_items IS
    'Share of a work day allocated to a Marketing, Sales, Finances, or Development effort.';

-- Safe to re-run after the table was created without a department.
ALTER TABLE public.employee_daily_effort_allocation_items
    ADD COLUMN IF NOT EXISTS department_id bigint;

COMMENT ON COLUMN public.employee_daily_effort_allocation_items.department_id IS
    'First chosen department, kept for older reads. NULL means General. Prefer department_ids.';

-- Several departments per effort. Re-run is safe.
ALTER TABLE public.employee_daily_effort_allocation_items
    ADD COLUMN IF NOT EXISTS department_ids bigint[] NOT NULL DEFAULT '{}';

UPDATE public.employee_daily_effort_allocation_items
SET department_ids = ARRAY[department_id]
WHERE department_id IS NOT NULL
  AND cardinality(department_ids) = 0;

COMMENT ON COLUMN public.employee_daily_effort_allocation_items.department_ids IS
    'Agreement-signed scoreboard departments this time is for. Empty means General.';

DO $$
