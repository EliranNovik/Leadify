-- Files attached to a manual "tax invoice sent" mark on a payment row.
-- Run after sql/2026-10-08_payment_plans_tax_invoice_sent.sql, which adds the mark itself.
--
-- A tax invoice paid through a payment link is issued by Payper and lives in payment_links; these
-- are the invoices issued outside that flow, where the only copy is the file the handler has.
--
-- Note: do NOT run ALTER TABLE storage.objects. Supabase manages RLS there; only add policies.

INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
VALUES (
  'payment-plan-tax-invoice-documents',
  'payment-plan-tax-invoice-documents',
  false,
  15728640,
  ARRAY[
    'image/jpeg',
    'image/jpg',
    'image/png',
    'image/gif',
    'image/webp',
    'application/pdf',
    'application/msword',
    'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
    'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
    'application/vnd.ms-excel'
  ]
)
ON CONFLICT (id) DO UPDATE SET
  public = false,
  file_size_limit = 15728640,
  allowed_mime_types = EXCLUDED.allowed_mime_types;

DROP POLICY IF EXISTS "payment-plan-tax-invoice-documents insert" ON storage.objects;
DROP POLICY IF EXISTS "payment-plan-tax-invoice-documents select" ON storage.objects;
DROP POLICY IF EXISTS "payment-plan-tax-invoice-documents update" ON storage.objects;
DROP POLICY IF EXISTS "payment-plan-tax-invoice-documents delete" ON storage.objects;

CREATE POLICY "payment-plan-tax-invoice-documents insert" ON storage.objects
  FOR INSERT TO authenticated
  WITH CHECK (bucket_id = 'payment-plan-tax-invoice-documents');

CREATE POLICY "payment-plan-tax-invoice-documents select" ON storage.objects
  FOR SELECT TO authenticated
  USING (bucket_id = 'payment-plan-tax-invoice-documents');

CREATE POLICY "payment-plan-tax-invoice-documents update" ON storage.objects
  FOR UPDATE TO authenticated
  USING (bucket_id = 'payment-plan-tax-invoice-documents')
  WITH CHECK (bucket_id = 'payment-plan-tax-invoice-documents');

CREATE POLICY "payment-plan-tax-invoice-documents delete" ON storage.objects
  FOR DELETE TO authenticated
  USING (bucket_id = 'payment-plan-tax-invoice-documents');

-- There is deliberately no foreign key on payment_plan_id: a payment row lives in payment_plans for
-- a new lead and in finances_paymentplanrow for a legacy one, and the ids of the two overlap. The
-- pair (is_legacy, payment_plan_id) is what identifies a row, so both are always needed to query.
CREATE TABLE IF NOT EXISTS public.payment_plan_tax_invoice_documents (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  payment_plan_id bigint NOT NULL,
  is_legacy boolean NOT NULL DEFAULT false,
  file_name text NOT NULL,
  mime_type text,
  file_size bigint,
  storage_path text NOT NULL,
  uploaded_by uuid REFERENCES auth.users (id) ON DELETE SET NULL,
  -- Mirrors payment_plans.tax_invoice_sent_by so the drawer can name the uploader the same way it
  -- names whoever recorded the send.
  uploaded_by_employee_id bigint
);

CREATE INDEX IF NOT EXISTS idx_pp_tax_invoice_docs_plan
  ON public.payment_plan_tax_invoice_documents (is_legacy, payment_plan_id, created_at DESC);

CREATE UNIQUE INDEX IF NOT EXISTS idx_pp_tax_invoice_docs_storage_path
  ON public.payment_plan_tax_invoice_documents (storage_path);

COMMENT ON TABLE public.payment_plan_tax_invoice_documents IS
  'Tax invoice files attached by hand to a payment row. Keyed by (is_legacy, payment_plan_id): false = public.payment_plans, true = public.finances_paymentplanrow.';
COMMENT ON COLUMN public.payment_plan_tax_invoice_documents.is_legacy IS
  'TRUE when payment_plan_id refers to finances_paymentplanrow rather than payment_plans.';

ALTER TABLE public.payment_plan_tax_invoice_documents ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "pp_tax_invoice_documents_select" ON public.payment_plan_tax_invoice_documents;
CREATE POLICY "pp_tax_invoice_documents_select"
  ON public.payment_plan_tax_invoice_documents
  FOR SELECT TO authenticated
  USING (true);

DROP POLICY IF EXISTS "pp_tax_invoice_documents_insert" ON public.payment_plan_tax_invoice_documents;
CREATE POLICY "pp_tax_invoice_documents_insert"
  ON public.payment_plan_tax_invoice_documents
  FOR INSERT TO authenticated
  WITH CHECK (auth.uid() IS NOT NULL AND (uploaded_by IS NULL OR uploaded_by = auth.uid()));

DROP POLICY IF EXISTS "pp_tax_invoice_documents_delete" ON public.payment_plan_tax_invoice_documents;
CREATE POLICY "pp_tax_invoice_documents_delete"
  ON public.payment_plan_tax_invoice_documents
  FOR DELETE TO authenticated
  USING (uploaded_by = auth.uid() OR public.is_app_superuser());

GRANT SELECT, INSERT, DELETE ON public.payment_plan_tax_invoice_documents TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.payment_plan_tax_invoice_documents_id_seq TO authenticated;

