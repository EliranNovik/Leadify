export function translatePortalDynamicLabel(
  locale: string | undefined,
  value: string | null | undefined,
  hebrewValue?: string | null,
): string {
  const raw = (value || '').trim();
  const hebrew = (hebrewValue || '').trim();
  if ((locale || 'en').toLowerCase().startsWith('he')) {
    if (hebrew) return hebrew;
    if (!raw) return raw;
    const translated = PORTAL_HE_LABELS[normalizePortalLabelKey(raw)];
    if (translated) return translated;
  }
  return raw;
}

