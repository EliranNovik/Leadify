/**
 * Reads cell formatting out of an .xlsx file's own XML.
 *
 * Why by hand, when the app already has a spreadsheet library: neither `xlsx` nor `xlsx-js-style`
 * gives this back on read. Both collapse a cell's style to its fill — a cell with red bold 16pt
 * centred text reads back as `{patternType: 'none'}` — so a handler's uploaded sheet arrived in the
 * app having lost its text colours and its alignment. The writers are fine; only reading is blind.
 *
 * An .xlsx is a zip of XML, and the part of it that holds formatting is small and regular:
 *
 *   xl/styles.xml   fonts, fills, borders, and `cellXfs` — the numbered styles cells point at
 *   xl/theme1.xml   the colour scheme that `theme="4"` refers to
 *   the sheet XML   `<c r="B7" s="12">`, where `s` is an index into `cellXfs`
 *
 * Parsed with regular expressions rather than a DOM, deliberately: these files are generated by
 * other programs rather than written by hand, and the module has to run both in the browser and
 * under the test runner, where there is no DOMParser.
 *
 * Nothing here trusts the file. Colours are returned only if they are six hex digits, sizes only
 * if they are sane numbers, and an unreadable style is dropped rather than guessed at.
 */

/** Horizontal alignment, as this app models it. Excel's other modes have no equivalent here. */
export type XlsxAlign = 'left' | 'center' | 'right';

/** One cell's formatting, as far as the file declares it. Absent means "not specified". */
export type XlsxCellStyle = {
  /** Background fill, as `#rrggbb`. */
  fill?: string;
  /** Text colour, as `#rrggbb`. Absent for Excel's "Automatic", which is not a colour. */
  fontColor?: string;
  bold?: boolean;
  italic?: boolean;
  underline?: boolean;
  /** In points, the unit the file uses. */
  fontSizePt?: number;
  align?: XlsxAlign;
  borderTop?: boolean;
  borderRight?: boolean;
  borderBottom?: boolean;
  borderLeft?: boolean;
};

/**
 * The legacy indexed palette, for `<color indexed="n"/>`.
 *
 * Fixed by the file format rather than by the document, so it is a constant. Only the first 56
 * entries are real colours; 64 and 65 mean "system foreground/background", which this app treats
 * as unspecified rather than painting them.
 */
const INDEXED_PALETTE: string[] = [
  '#000000', '#ffffff', '#ff0000', '#00ff00', '#0000ff', '#ffff00', '#ff00ff', '#00ffff',
  '#000000', '#ffffff', '#ff0000', '#00ff00', '#0000ff', '#ffff00', '#ff00ff', '#00ffff',
  '#800000', '#008000', '#000080', '#808000', '#800080', '#008080', '#c0c0c0', '#808080',
  '#9999ff', '#993366', '#ffffcc', '#ccffff', '#660066', '#ff8080', '#0066cc', '#ccccff',
  '#000080', '#ff00ff', '#ffff00', '#00ffff', '#800080', '#800000', '#008080', '#0000ff',
  '#00ccff', '#ccffff', '#ccffcc', '#ffff99', '#99ccff', '#ff99cc', '#cc99ff', '#ffcc99',
  '#3366ff', '#33cccc', '#99cc00', '#ffcc00', '#ff9900', '#ff6600', '#666699', '#969696',
  '#003366', '#339966', '#003300', '#333300', '#993300', '#993366', '#333399', '#333333',
];

/**
 * The order `<a:clrScheme>` entries map onto `theme="n"`.
 *
 * Not the document order: Excel swaps the first two pairs, so theme 0 is the *light* background and
 * theme 1 the dark text, which is the opposite of how the scheme lists them.
 */
const THEME_ORDER = [
  'lt1',
  'dk1',
  'lt2',
  'dk2',
  'accent1',
  'accent2',
  'accent3',
  'accent4',
  'accent5',
  'accent6',
  'hlink',
  'folHlink',
];

/** Namespace prefixes vary between the programs that write these files; the tag names do not. */
function stripNamespaces(xml: string): string {
  return xml.replace(/<(\/?)[a-zA-Z0-9]+:/g, '<$1');
}

function attribute(tag: string, name: string): string | undefined {
  const match = tag.match(new RegExp(`\\s${name}\\s*=\\s*"([^"]*)"`));
  return match ? match[1] : undefined;
}

/**
 * Splits a container's direct children into their source text.
 *
 * Handles both `<font/>` and `<font>...</font>`, and nests correctly for `<border>` inside
 * `<borders>`, by counting depth rather than matching the first closing tag.
 */
function childBlocks(container: string, tagName: string): string[] {
  const blocks: string[] = [];
  /*
   * The lookahead is what keeps the tag name whole: scanning a row's cells for `<c`, a plain
   * substring search would also stop on `<col`, and the element would be cut short at a tag that
   * has nothing to do with it.
   */
  const token = new RegExp(`<(/?)${tagName}(?=[\\s/>])[^>]*>`, 'g');

  let depth = 0;
  let start = 0;
  let match = token.exec(container);

  while (match) {
    const closing = match[1] === '/';
    const selfClosing = match[0].endsWith('/>');

    if (closing) {
      depth -= 1;
      if (depth === 0) blocks.push(container.slice(start, token.lastIndex));
    } else if (selfClosing) {
      if (depth === 0) blocks.push(match[0]);
    } else {
      if (depth === 0) start = match.index;
      depth += 1;
    }

    match = token.exec(container);
  }

  return blocks;
}

/** The content of the first `<tagName>` element, used for the one-of-a-kind containers. */
function section(xml: string, tagName: string): string {
  const match = xml.match(new RegExp(`<${tagName}(?:\\s[^>]*)?>([\\s\\S]*?)</${tagName}>`));
  return match ? match[1] : '';
}

function normalizeHex(value: string | undefined): string | undefined {
  if (!value) return undefined;
  const text = value.trim().toLowerCase();
  // Eight digits carry an alpha channel first; only the colour is wanted.
  const hex = text.length === 8 ? text.slice(2) : text;
  return /^[0-9a-f]{6}$/.test(hex) ? `#${hex}` : undefined;
}

function toRgb(hex: string): { r: number; g: number; b: number } {
  return {
    r: parseInt(hex.slice(1, 3), 16),
    g: parseInt(hex.slice(3, 5), 16),
    b: parseInt(hex.slice(5, 7), 16),
  };
}

function toHex(r: number, g: number, b: number): string {
  const clamp = (value: number) =>
    Math.max(0, Math.min(255, Math.round(value)))
      .toString(16)
      .padStart(2, '0');
  return `#${clamp(r)}${clamp(g)}${clamp(b)}`;
}

/**
 * Applies a theme colour's `tint`, which is how Excel stores "accent 1, 40% lighter".
 *
 * Excel's own definition, in terms of luminance: a positive tint moves the channel towards white by
 * that fraction, a negative one towards black. Applied per channel, which is equivalent for the
 * greys and close enough elsewhere that a cell reads as the shade its author picked.
 */
function applyTint(hex: string, tint: number): string {
  if (!Number.isFinite(tint) || tint === 0) return hex;
  const { r, g, b } = toRgb(hex);
  const shift = (channel: number) =>
    tint > 0 ? channel + (255 - channel) * tint : channel * (1 + tint);
  return toHex(shift(r), shift(g), shift(b));
}

/** The theme's colour scheme, keyed the way `theme="n"` indexes it. */
function parseTheme(themeXml: string | undefined): string[] {
  if (!themeXml) return [];

  const scheme = section(stripNamespaces(themeXml), 'clrScheme');
  if (!scheme) return [];

  return THEME_ORDER.map((name) => {
    const entry = section(scheme, name);
    if (!entry) return '';
    const srgb = entry.match(/<srgbClr[^>]*\sval\s*=\s*"([^"]*)"/);
    if (srgb) return normalizeHex(srgb[1]) ?? '';
    // A system colour carries its resolved value, which is the usable part of it.
    const sys = entry.match(/<sysClr[^>]*\slastClr\s*=\s*"([^"]*)"/);
    return sys ? normalizeHex(sys[1]) ?? '' : '';
  });
}

/**
 * Resolves one `<color>` element, whichever of the four ways it names its colour.
 *
 * `auto="1"` returns nothing on purpose: it means "whatever the program's default is", so treating
 * it as black would stamp a colour onto cells whose author never chose one, and that colour would
 * then be saved and exported as though they had.
 */
function parseColor(tag: string | undefined, theme: string[]): string | undefined {
  if (!tag) return undefined;
  if (attribute(tag, 'auto') === '1') return undefined;

  const rgb = normalizeHex(attribute(tag, 'rgb'));
  if (rgb) return rgb;

  const themeIndex = Number(attribute(tag, 'theme'));
  if (Number.isInteger(themeIndex) && themeIndex >= 0) {
    const base = theme[themeIndex];
    if (base) return applyTint(base, Number(attribute(tag, 'tint') ?? 0));
  }

  const indexed = Number(attribute(tag, 'indexed'));
  if (Number.isInteger(indexed) && indexed >= 0 && indexed < INDEXED_PALETTE.length) {
    return INDEXED_PALETTE[indexed];
  }

  return undefined;
}

function firstTag(xml: string, tagName: string): string | undefined {
  const match = xml.match(new RegExp(`<${tagName}(?:\\s[^>]*?)?/?>`));
  return match ? match[0] : undefined;
}

/**
 * Whether a boolean font property is on.
 *
 * `<b/>` means bold, and so does `<b val="1"/>`, but `<b val="0"/>` means the opposite — a file
 * that spells out "not bold" must not be read as bold just because the element is present.
 */
function booleanProperty(fontXml: string, tagName: string): boolean {
  const tag = firstTag(fontXml, tagName);
  if (!tag) return false;
  const value = attribute(tag, 'val');
  return value === undefined || value === '1' || value === 'true';
}

type ParsedFont = {
  color?: string;
  bold: boolean;
  italic: boolean;
  underline: boolean;
  sizePt?: number;
};

function parseFonts(stylesXml: string, theme: string[]): ParsedFont[] {
  return childBlocks(section(stylesXml, 'fonts'), 'font').map((font) => {
    const size = Number(attribute(firstTag(font, 'sz') ?? '', 'val'));
    return {
      color: parseColor(firstTag(font, 'color'), theme),
      bold: booleanProperty(font, 'b'),
      italic: booleanProperty(font, 'i'),
      // `<u val="none"/>` is Excel's way of switching it off again.
      underline:
        booleanProperty(font, 'u') && attribute(firstTag(font, 'u') ?? '', 'val') !== 'none',
      sizePt: Number.isFinite(size) && size > 0 ? size : undefined,
    };
  });
}

function parseFills(stylesXml: string, theme: string[]): (string | undefined)[] {
  return childBlocks(section(stylesXml, 'fills'), 'fill').map((fill) => {
    const pattern = firstTag(fill, 'patternFill');
    const type = pattern ? attribute(pattern, 'patternType') : undefined;
    // Only a solid fill is a background colour; the hatch patterns are not colours this app has.
    if (type !== 'solid') return undefined;

    const fg = parseColor(firstTag(fill, 'fgColor'), theme);
    if (fg) return fg;
    /*
     * A solid fill with only a background colour happens, and the two are swapped relative to how
     * they read: for `solid`, fgColor is the visible one, so bgColor is a fallback, not a blend.
     */
    return parseColor(firstTag(fill, 'bgColor'), theme);
  });
}

type ParsedBorder = { top: boolean; right: boolean; bottom: boolean; left: boolean };

function parseBorders(stylesXml: string): ParsedBorder[] {
  return childBlocks(section(stylesXml, 'borders'), 'border').map((border) => {
    const edge = (name: string) => {
      const tag = firstTag(border, name);
      if (!tag) return false;
      const style = attribute(tag, 'style');
      return Boolean(style) && style !== 'none';
    };
    return { top: edge('top'), right: edge('right'), bottom: edge('bottom'), left: edge('left') };
  });
}

function parseAlign(xf: string): XlsxAlign | undefined {
  const tag = firstTag(xf, 'alignment');
  if (!tag) return undefined;
  const horizontal = attribute(tag, 'horizontal');
  if (horizontal === 'center' || horizontal === 'centerContinuous') return 'center';
  if (horizontal === 'right') return 'right';
  if (horizontal === 'left') return 'left';
  // 'general' means "decide from the content", which is what the app does when nothing is set.
  return undefined;
}

/**
 * The numbered styles a sheet's cells point at.
 *
 * Exported so a caller can resolve a style index itself, but the useful entry point is
 * `readXlsxCellStyles`.
 */
export function parseXlsxStyleTable(
  stylesXml: string,
  themeXml?: string,
): XlsxCellStyle[] {
  const styles = stripNamespaces(stylesXml ?? '');
  const theme = parseTheme(themeXml);

  const fonts = parseFonts(styles, theme);
  const fills = parseFills(styles, theme);
  const borders = parseBorders(styles);

  return childBlocks(section(styles, 'cellXfs'), 'xf').map((xf) => {
    const style: XlsxCellStyle = {};

    const font = fonts[Number(attribute(xf, 'fontId') ?? -1)];
    if (font) {
      if (font.color) style.fontColor = font.color;
      if (font.bold) style.bold = true;
      if (font.italic) style.italic = true;
      if (font.underline) style.underline = true;
      if (font.sizePt) style.fontSizePt = font.sizePt;
    }

    const fill = fills[Number(attribute(xf, 'fillId') ?? -1)];
    if (fill) style.fill = fill;

    const border = borders[Number(attribute(xf, 'borderId') ?? -1)];
    if (border) {
      if (border.top) style.borderTop = true;
      if (border.right) style.borderRight = true;
      if (border.bottom) style.borderBottom = true;
      if (border.left) style.borderLeft = true;
    }

    const align = parseAlign(xf);
    if (align) style.align = align;

    return style;
  });
}

/**
 * Where each sheet's XML lives inside the zip, in the order the workbook lists its sheets.
 *
 * Worth resolving properly rather than assuming `xl/worksheets/sheet1.xml`: the file numbers its
 * parts in creation order, so the first *listed* sheet of a workbook whose tabs have been reordered
 * or deleted can be `sheet3.xml`, and reading the wrong part would apply one sheet's formatting to
 * another's cells.
 */
export function sheetPartPaths(workbookXml: string, relsXml: string): string[] {
  const targets = new Map<string, string>();

  for (const relationship of childBlocks(
    stripNamespaces(relsXml ?? ''),
    'Relationship',
  )) {
    const id = attribute(relationship, 'Id');
    const target = attribute(relationship, 'Target');
    if (id && target) targets.set(id, target);
  }

  const sheets = childBlocks(section(stripNamespaces(workbookXml ?? ''), 'sheets'), 'sheet');

  return sheets
    .map((sheet) => {
      const id = attribute(sheet, 'r:id') ?? attribute(sheet, 'id');
      const target = id ? targets.get(id) : undefined;
      if (!target) return '';
      // A target is either absolute within the package or relative to the workbook part's folder.
      return target.startsWith('/') ? target.slice(1) : `xl/${target.replace(/^\.\//, '')}`;
    })
    .filter(Boolean);
}

/** `B7` to row 6, column 1. Returns null for anything that is not a cell reference. */
export function decodeCellRef(ref: string): { rowIndex: number; colIndex: number } | null {
  const match = /^([A-Z]+)(\d+)$/.exec(String(ref ?? '').trim().toUpperCase());
  if (!match) return null;

  let colIndex = 0;
  for (const letter of match[1]) {
    colIndex = colIndex * 26 + (letter.charCodeAt(0) - 64);
  }

  const rowIndex = Number(match[2]) - 1;
  if (rowIndex < 0 || colIndex < 1) return null;
  return { rowIndex, colIndex: colIndex - 1 };
}

/**
 * Every styled cell in one sheet, keyed `row:col` with zero-based sheet coordinates.
 *
 * A row can carry a style of its own (`<row s="3" customFormat="1">`), which is how a whole
 * formatted row arrives when its cells are empty, and that is used as the starting point for each
 * cell in the row so a cell's own style still wins.
 */
export function readXlsxCellStyles(
  stylesXml: string,
  sheetXml: string,
  themeXml?: string,
): Map<string, XlsxCellStyle> {
  const table = parseXlsxStyleTable(stylesXml, themeXml);
  const styles = new Map<string, XlsxCellStyle>();
  if (table.length === 0) return styles;

  const sheet = stripNamespaces(sheetXml ?? '');

  for (const row of childBlocks(section(sheet, 'sheetData'), 'row')) {
    const rowHeader = firstTag(row, 'row') ?? '';
    const rowNumber = Number(attribute(rowHeader, 'r'));
    const rowStyle =
      attribute(rowHeader, 'customFormat') === '1' || attribute(rowHeader, 's') !== undefined
        ? table[Number(attribute(rowHeader, 's') ?? -1)]
        : undefined;

    for (const cell of childBlocks(row, 'c')) {
      const header = firstTag(cell, 'c') ?? '';
      const ref = attribute(header, 'r');

      const position = ref ? decodeCellRef(ref) : null;
      if (!position || !Number.isInteger(rowNumber)) continue;

      /*
       * A cell's own style index replaces the row's rather than adding to it: in this format an
       * index names a cell's complete format, so a cell that points at one is fully described by
       * it. Merging the two would leak a formatted row's bold onto cells that were given a
       * different format on purpose.
       */
      const own = table[Number(attribute(header, 's') ?? -1)];
      const resolved = own ?? rowStyle;
      if (!resolved || Object.keys(resolved).length === 0) continue;

      styles.set(`${position.rowIndex}:${position.colIndex}`, resolved);
    }
  }

  return styles;
}
